/** Labels the seed writes in French, with their English. */
export const SEEDED_IN_FRENCH: Record<
	CategoryLabelKind,
	Record<string, string>
> = {
	name: {},
	description: {},
	attribute: { État: "Condition" },
	group: {},
	option: {
		Neuf: "New",
		"Comme neuf": "Like new",
		"Bon état": "Good condition",
		"État correct": "Fair condition",
		"Mauvais état": "Poor condition",
	},
	priceLabel: {},
	unit: {},
};

const ENGLISH_OF_FRENCH: Record<
	CategoryLabelKind,
	Map<string, string>
> = Object.fromEntries(
	(Object.keys(CATEGORY_LABELS_FR) as CategoryLabelKind[]).map((kind) => [
		kind,
		new Map<string, string>([
			...Object.entries(CATEGORY_LABELS_FR[kind]).map(
				([en, fr]) => [fr, en] as [string, string],
			),
			...Object.entries(SEEDED_IN_FRENCH[kind]),
		]),
	]),
) as Record<CategoryLabelKind, Map<string, string>>;

export interface LocalizedLabel {
	fr: string;
	en: string;
}

/**
 * Both languages of a seeded label, recognised from either its English seed
 * wording or its French; `null` for anything the seed never wrote.
 */
export function seedLabelTranslation(
	kind: CategoryLabelKind,
	value: string,
): LocalizedLabel | null {
	const fr = CATEGORY_LABELS_FR[kind][value];
	if (fr !== undefined) return { fr, en: value };
	const en = ENGLISH_OF_FRENCH[kind].get(value);
	if (en !== undefined) return { fr: value, en };
	return null;
}

/** The English of a French seed word; undefined for anything else. */
export function seedEnglishOfFrench(
	kind: CategoryLabelKind,
	value: string,
): string | undefined {
	return ENGLISH_OF_FRENCH[kind].get(value);
}

/** The French of an English seed word; undefined for anything else. */
export function seedFrenchOfEnglish(
	kind: CategoryLabelKind,
	value: string,
): string | undefined {
	return Object.hasOwn(CATEGORY_LABELS_FR[kind], value)
		? CATEGORY_LABELS_FR[kind][value]
		: undefined;
}

/** The French a seed string is written with in the default locale. */
export function seedLabelFr(kind: CategoryLabelKind, value: string): string {
	return CATEGORY_LABELS_FR[kind][value] ?? value;
}

interface SeedAttributeShape {
	name: string;
	group?: string;
	unit?: string;
	options?: { value: string; label?: string }[];
}

/** A seed attribute worded in French, for writing into the default locale. */
export function frenchSeedAttribute<T extends SeedAttributeShape>(
	attribute: T,
): T {
	return {
		...attribute,
		name: seedLabelFr("attribute", attribute.name),
		...(attribute.group
			? { group: seedLabelFr("group", attribute.group) }
			: {}),
		...(attribute.unit ? { unit: seedLabelFr("unit", attribute.unit) } : {}),
		...(attribute.options
			? {
					options: attribute.options.map((option) => {
						if (option.label) return option;
						const fr = CATEGORY_LABELS_FR.option[option.value];
						return fr ? { ...option, label: fr } : option;
					}),
				}
			: {}),
	};
}
